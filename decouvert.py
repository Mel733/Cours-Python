#       fonction ou une classe (ex. une seule méthode attaquer() pour les deux personnages).

# KISS = Keep It Simple, Stupid : garder le code simple, éviter la complexité inutile.

# SOLID = 5 principes de conception orientée objet :
#       S : Single Responsibility (une classe = une seule responsabilité)
#       O : Open/Closed (ouvert à l'extension, fermé à la modification)
#       L : Liskov Substitution (une classe fille doit pouvoir remplacer sa mère)
#       I : Interface Segregation (plusieurs petites interfaces plutôt qu'une grosse)
#       D : Dependency Inversion (dépendre d'abstractions, pas de classes concrètes)

# YAGNI = You Aren't Gonna Need It : ne pas coder ce dont on n'a pas besoin
#       maintenant. Rejoint KISS (rester simple).





